#pragma once

/**
 * @brief Абстрактный базовый класс генератора значений
 * 
 * Описывает интерфейс для получения int-значений.
 * Конкретные способы генерации (случайные, с клавиатуры, константные)
 * реализуются в классах-наследниках.
 * 
 * Используется для заполнения матриц по заданному алгоритму.
 */
class Generator
{
public:
    /**
     * @brief Виртуальный деструктор
     * 
     * Объявлен виртуальным для корректного удаления объектов
     * наследников через указатель на базовый класс.
     */
    virtual ~Generator() = default;

    /**
     * @brief Сгенерировать следующее значение
     * 
     * Чисто виртуальный метод. Каждый наследник обязан
     * реализовать свою логику генерации.
     * 
     * @return сгенерированное целое число
     */
    virtual int generate() = 0;
};
